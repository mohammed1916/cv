import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse } from '@babel/parser';
import assert from 'node:assert/strict';
import { definitionSources as dependencies, definitionOrigins as origins } from '../src/problems/families/collectionStories/definitionSources.js';

const dir=path.resolve('src/problems/families/collectionStories');
const source=fs.readFileSync(path.join(dir,'createDefinitions.js'),'utf8');
const before=dependencies.specs;
const groups=[];
const authoredSource=fs.readFileSync(path.join(dir,'authoredBatches.js'),'utf8');
for(const node of parse(authoredSource,{sourceType:'module'}).program.body.filter(n=>n.type==='ImportDeclaration')) {
 const {default:batch}=await import(pathToFileURL(path.resolve(dir,node.source.value)));
 groups.push({name:path.basename(node.source.value,'.js'),ids:Object.keys(batch.specs),batch,path:node.source.value,kind:'authored'});
}
const checks=[...source.matchAll(/if \(id in (\w+)\) return (\w+)\(id,input\);/g)].filter(m=>m[1]!=='authoredSpecs');
for(const[,map,validator]of checks)groups.push({name:map.replace(/Specs$/,''),ids:Object.keys(dependencies[map]).filter(id=>!groups.some(g=>g.ids.includes(id))),map,validator});
groups.push({name:'base',ids:Object.keys(before).filter(id=>!groups.some(g=>g.ids.includes(id)))});

// Keep base solver helpers verbatim, but stop importing every unrelated solver map.
let algorithms=fs.readFileSync(path.join(dir,'algorithms.js'),'utf8');
algorithms=algorithms.replace(/^import .*\r?\n/gm,'').replace(/^\s*\.\.\.\w+,\r?\n/gm,'');
fs.writeFileSync(path.join(dir,'baseAlgorithms.js'),'// Generated by npm run build:definition-groups; edit algorithms.js instead.\n'+algorithms);

fs.mkdirSync(path.join(dir,'definitionGroups'),{recursive:true});
const routeGroups={};
for(const group of groups) {
 assert.ok(group.ids.length,`Empty definition group ${group.name}`);
 for(const id of group.ids)assert.ok(!(id in routeGroups),`Duplicate definition ${id} in ${group.name}`);
 const ids=new Set(group.ids), pick=map=>Object.fromEntries(Object.entries(map).filter(([id])=>ids.has(id)));
 const values={}, imports=[`import { createDefinitions } from '../createDefinitions.js';`], props=[];
 // Static metadata and teaching code belong to the batch, not a global browser registry.
 for(const[key,value]of Object.entries(dependencies))if(typeof value==='object'&&key!=='solvers'&&key!=='collectionStoryExamples') {
  const subset=pick(value);if(Object.keys(subset).length)values[key]=subset;
 }
 for(const[id,index]of group.ids.map((id,i)=>[id,i])) {
  imports.push(`import examples${index} from '../../../../config/examples/collection--${id}.js';`);
  routeGroups[id]=group.name;
 }
 props.push(`collectionStoryExamples: {${group.ids.map((id,i)=>`${id}: examples${i}`).join(',')}}`);
 if(group.kind==='authored') {
  imports.push(`import batch from '.${group.path}';`);
  props.push('solvers: batch.solvers','validateAuthored: batch.validate',
   "authoredResultStage: (id,result,input) => batch.resultStage?.(id,result,input) ?? 'return'",
   'authoredInputState: (id,input) => batch.inputState?.(id,input) ?? {}',
   'authoredResultState: (id,result) => batch.resultState?.(id,result) ?? {}');
 } else {
  if(group.validator) {
   imports.push(`import { ${group.validator} } from '.${origins[group.validator]}';`);
   props.push(group.validator);
  }
  // Discover the owning solver export by identity, without duplicating implementations.
  if(group.name==='base') {imports.push("import { solvers } from '../baseAlgorithms.js';");props.push('solvers');}
  else {
   const algorithmAst=parse(fs.readFileSync(path.join(dir,'algorithms.js'),'utf8'),{sourceType:'module'});
   let found=false;
   for(const node of algorithmAst.program.body.filter(n=>n.type==='ImportDeclaration'&&!n.source.value.includes('authoredBatches'))) {
    const mod=await import(pathToFileURL(path.resolve(dir,node.source.value)));
    for(const s of node.specifiers)if(group.ids.every(id=>mod[s.imported.name]?.[id]===dependencies.solvers[id])) {
     imports.push(`import { ${s.imported.name} as solvers } from '.${node.source.value}';`);props.push('solvers');found=true;break;
    }
    if(found)break;
   }
   assert.ok(found,`Solver module for ${group.name}`);
  }
  const extras={database:['databaseInput'],range:['rangeCodeStage'],broad:['broadResultStage']}[group.name]??[];
  for(const key of extras){imports.push(`import { ${key} } from '.${origins[key]}';`);props.push(key);}
 }
 fs.writeFileSync(path.join(dir,'definitionGroups',group.name+'.js'),
  '// Generated by npm run build:definition-groups; edit the source batch instead.\n'+imports.join('\n')+'\n\nexport const definitions = createDefinitions({\n'+
  Object.entries(values).map(([key,value])=>`  ${key}: ${JSON.stringify(value)},`).join('\n')+'\n  '+props.join(',\n  ')+'\n});\n');
}

fs.writeFileSync(path.join(dir,'definitions.js'), '// Tooling-only aggregate. Browser routes import a definitionGroups module.\n'+
 groups.map((g,i)=>`import { definitions as group${i} } from './definitionGroups/${g.name}.js';`).join('\n')+
 '\nexport const definitions = Object.assign({}, '+groups.map((_,i)=>`group${i}`).join(', ')+');\n');
fs.writeFileSync(path.join(dir,'definitionGroupIndex.json'),JSON.stringify(routeGroups,null,2)+'\n');
console.log(`Generated ${Object.keys(before).length} collection definitions in ${groups.length} independently loaded groups.`);
